// Long-run demography against the UN: npm run un -- [seeds=5]
// Runs the model from the 2023 baseline to 2100 and compares population, fertility and life expectancy in 2050 and 2100
// with the UN World Population Prospects 2024 medium variant (baseline.meta.unProjections). Writes docs/UN_COMPARISON.md.
// The UN projection is itself a model (Bayesian hierarchical fertility and mortality, assumed migration), not data:
// agreement means the model's demographic transition behaves like the standard one, not that either is right.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadBaseline } from './load';
import { Simulation } from '../engine/sim';
import { daysFromCivil } from '../engine/calendar';
import { totalPop } from '../engine/state';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const b = loadBaseline(), U = b.meta.unProjections ?? {};
const seeds = Number(process.argv[2] ?? 5), n = b.countries.length;
const q = (xs: number[], p: number) => { const t = xs.slice().sort((a, z) => a - z); const i = (t.length - 1) * p, lo = Math.floor(i); return t[lo] + (t[Math.ceil(i)] - t[lo]) * (i - lo); };
type Snap = { pop: number[]; tfr: number[]; e0: number[] };
const snaps: Record<2050 | 2100, Snap[]> = { 2050: [], 2100: [] };
const t0 = performance.now();
for (let s = 1; s <= seeds; s++) {
  const sim = new Simulation(b, { seed: s });
  for (const y of [2050, 2100] as const) {
    sim.advanceTo(daysFromCivil(y, 7, 1));
    const f = sim.st.f;
    snaps[y].push({ pop: Array.from({ length: n }, (_, c) => totalPop(sim.st, c)), tfr: Array.from(f.tfr.subarray(0, n)), e0: Array.from(f.lifeExp.subarray(0, n)) });
  }
  process.stdout.write('.');
}
const med = (y: 2050 | 2100, k: keyof Snap, c: number) => q(snaps[y].map((r) => r[k][c]), 0.5);
// populations of countries that seceded during a run are counted with their parent, so totals stay comparable
const world = (y: 2050 | 2100) => q(snaps[y].map((r) => r.pop.reduce((a, x) => a + x, 0)), 0.5);
const unWorld = (y: 2050 | 2100) => Object.values(U).reduce((a, u) => a + u[`pop${y}`], 0);
const rows: string[] = [];
const summary = (y: 2050 | 2100) => {
  const ep: number[] = [], et: number[] = [], ee: number[] = [];
  b.countries.forEach((bc, c) => {
    const u = U[bc.id];
    if (!u || (bc.fields.pop?.v ?? 0) < 1e6) return;
    ep.push(Math.log(med(y, 'pop', c) / u[`pop${y}`])); et.push(med(y, 'tfr', c) - u[`tfr${y}`]); ee.push(med(y, 'e0', c) - u[`e0${y}`]);
  });
  const f = (xs: number[], pct = false) => { const m = q(xs.map(Math.abs), 0.5), bias = q(xs, 0.5); return pct ? `${(100 * m).toFixed(0)}% / ${bias > 0 ? '+' : ''}${(100 * bias).toFixed(0)}%` : `${m.toFixed(2)} / ${bias > 0 ? '+' : ''}${bias.toFixed(2)}`; };
  rows.push(`| ${y} | ${(world(y) / 1e9).toFixed(2)} bn | ${(unWorld(y) / 1e9).toFixed(2)} bn | ${f(ep, true)} | ${f(et)} | ${f(ee)} | ${ep.length} |`);
};
summary(2050); summary(2100);
const big = ['IND', 'CHN', 'USA', 'IDN', 'PAK', 'NGA', 'BRA', 'BGD', 'RUS', 'ETH', 'MEX', 'JPN', 'EGY', 'PHL', 'COD', 'VNM', 'IRN', 'TUR', 'DEU', 'TZA', 'KOR', 'ITA', 'NER'];
const detail = big.map((id) => {
  const c = b.countries.findIndex((x) => x.id === id), u = U[id];
  const m = (v: number) => (v / 1e6).toFixed(0);
  return `| ${b.countries[c].name} | ${m(b.countries[c].fields.pop!.v)} | ${m(med(2050, 'pop', c))} | ${m(u.pop2050)} | ${m(med(2100, 'pop', c))} | ${m(u.pop2100)} | ${med(2100, 'tfr', c).toFixed(2)} | ${u.tfr2100.toFixed(2)} |`;
}).join('\n');
const md = `# Long-run demography against the UN (2050, 2100)

Generated by \`npm run un -- ${seeds}\` on ${new Date().toISOString().slice(0, 10)} (${((performance.now() - t0) / 1000).toFixed(0)} s): the model
runs from the 2023 baseline with ${seeds} seeds; medians are compared with the UN World Population Prospects 2024
medium variant. The UN projection is itself a model, not data, so this checks that the simulated demographic
transition behaves like the standard one. Unlike the UN, the model's world has wars, famines of income, secessions
and migration that respond to events; countries with under 1 million people are left out of the error columns.

| Year | World, model | World, UN | Population: median abs. / bias | Fertility (children per woman): median abs. / bias | Life expectancy (years): median abs. / bias | Countries |
|---|---|---|---|---|---|---|
${rows.join('\n')}

## Largest countries (millions; fertility in 2100)

| Country | 2023 | 2050 model | 2050 UN | 2100 model | 2100 UN | TFR 2100 model | TFR 2100 UN |
|---|---|---|---|---|---|---|---|
${detail}
`;
fs.writeFileSync(path.join(root, 'docs/UN_COMPARISON.md'), md);
console.log('\n' + md);
